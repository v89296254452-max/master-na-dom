export function buildSeoDescription(category: Category, title: string, master: string): string {
  const theme = title.replace(/[.:].*$/, "").trim();
  let desc = DESC_TEMPLATES[category](theme, master.toLowerCase());
  if (desc.length > 155) desc = shortenAtWord(desc, 152) + "…";
  return desc;
}

export function buildKeywords(title: string, service: string): string {
  const stop = new Set([
    "и","в","на","до","что","как","не","или","это","для","к","о","по","при","из","за",
    "ли","со","от","же","бы","причины","решения",
  ]);
  const words = title
    .toLowerCase()
    .replace(/[^а-яёa-z0-9\s-]/gi, "")
    .split(/\s+/)
    .filter((w) => w.length > 2 && !stop.has(w))
    .slice(0, 5);
  const set = new Set<string>([...words, service.toLowerCase()]);
  return Array.from(set).join(";");
}

/* ----------------------------------------------------------------------------
 * Дата публикации: равномерный разброс за последние 18 месяцев
 * -------------------------------------------------------------------------- */

export function buildDate(index: number, total: number): string {
  const now = Date.now();
  const span = 18 * 30 * 24 * 60 * 60 * 1000;
  // распределяем + псевдослучайный сдвиг на основе индекса
  const base = (index + 1) / (total + 1);
  const jitter = ((index * 9301 + 49297) % 233280) / 233280 / total;
  const offset = Math.min(1, base + jitter * 0.5) * span;
  const d = new Date(now - offset);
  return d.toISOString().slice(0, 10);
}

