    `Подведём итог. ${cap(theme)} — решаемый вопрос, если действовать спокойно и по порядку: сначала исключить простые причины, затем оценить, безопасно ли продолжать самому. Не забывайте о профилактике — она дешевле и надёжнее любого ремонта.`
