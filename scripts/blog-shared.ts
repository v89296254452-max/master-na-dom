export type Category = "sovety" | "remont" | "vybor" | "ceny" | "instrukcia";

export function categorize(title: string): Category {
  const t = title.toLowerCase();
  if (/сколько стоит|цен[аы]|стоимость|расцен/.test(t)) return "ceny";
  if (/как выбрать| или |плюсы и минусы|что лучше|что выбрать|стоит ли|в чём разница/.test(t))
    return "vybor";
  if (
    /своими руками|пошагов|как (собрать|повесить|поклеить|подключить|установить|сделать|закрепить|настроить|прочистить|удалить|восстановить|устранить)|установка|монтаж|замена/.test(
      t
    )
  )
    return "instrukcia";
  if (
    /почему|не (включается|сливает|морозит|набирает|отжимает|крутится|выключается|загружается|видит|охлаждает|работает|реагирует)|ошибк|код|греется|искрит|теч|шумит|гремит|мигает|выбивает|перегрева|замыкание|нет (света|горячей)|плохо|слаб/.test(
      t
    )
  )
    return "remont";
  return "sovety";
}

const usedSlugs = new Set<string>();

export function resetSlugs() {
  usedSlugs.clear();
}

export function buildSlug(category: Category, title: string): string {
  const words = slugify(title).split("-").filter(Boolean).slice(0, 7).join("-");
  let base = `${category}-${words}`;
  if (base.length > 70) base = base.slice(0, 70).replace(/-[^-]*$/, "");
  let slug = base;
  let n = 2;
  while (usedSlugs.has(slug)) {
    slug = `${base}-${n++}`;
  }
  usedSlugs.add(slug);
  return slug;
}

