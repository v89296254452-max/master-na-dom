const BRAND = " | ПроМастер";

function shortenAtWord(text: string, max: number): string {
  if (text.length <= max) return text;
  const cut = text.slice(0, max);
  const lastSpace = cut.lastIndexOf(" ");
  return (lastSpace > max * 0.6 ? cut.slice(0, lastSpace) : cut).trim();
}

export function buildSeoTitle(title: string): string {
  if (title.length + BRAND.length <= 60) return `${title}${BRAND}`;
  if (title.length <= 60) return title;
  return shortenAtWord(title, 60);
}

