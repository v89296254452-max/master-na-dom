/* ----------------------------------------------------------------------------
 * Псевдослучайный генератор (детерминированный по slug)
 * -------------------------------------------------------------------------- */

function hash(str: string): number {
  let h = 2166136261;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

function mulberry32(seed: number) {
  return function () {
    seed |= 0;
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function shuffle<T>(arr: T[], rnd: () => number): T[] {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

function pick<T>(arr: T[], n: number, rnd: () => number): T[] {
  return shuffle(arr, rnd).slice(0, Math.min(n, arr.length));
}

function cap(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

function sentences(items: string[]): string {
  return items.map((s) => cap(s.trim().replace(/\.$/, "")) + ".").join(" ");
}

function bullets(items: string[]): string {
  return items.map((s) => `- ${cap(s.trim())}`).join("\n");
}

function numbered(items: string[]): string {
  return items.map((s, i) => `${i + 1}. ${cap(s.trim())}`).join("\n");
}

