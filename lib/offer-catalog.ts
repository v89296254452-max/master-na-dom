export const UNKNOWN_SERVICE = "Не знаю / подскажите";

export function getCalcService(name?: string): CalcService {
  return CALC_SERVICES.find((s) => s.name === name) ?? CALC_SERVICES[0];
}

/** Полный список услуг для селекта: значение страницы первым, без дублей. */
export function mergeServiceOptions(preferred?: string, extra: string[] = []): string[] {
  const all = [...OFFER_SERVICE_NAMES, ...extra];
  const rest = all.filter((v) => v && v !== preferred);
  return [...new Set([...(preferred ? [preferred] : []), ...rest])];
}

export function mergeCityOptions(preferred?: string, extra: string[] = []): string[] {
  const all = [...OFFER_CITIES, ...extra];
  const rest = all.filter((v) => v && v !== preferred);
  return [...new Set([...(preferred ? [preferred] : []), ...rest])];
}
